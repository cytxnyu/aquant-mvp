def build_theme_universe(themes: str | Iterable[str] = "hot") -> pd.DataFrame:
    selected = _resolve_theme_names(themes)
    rows: list[dict[str, object]] = []
    for theme in selected:
        if theme not in HOT_THEME_SYMBOLS:
            raise ValueError(f"Unknown theme: {theme}")
        for rank, (symbol, name, reason) in enumerate(HOT_THEME_SYMBOLS[theme], start=1):
            rows.append(
                {
                    "theme": theme,
                    "theme_group": _theme_group(theme),
                    "symbol": symbol,
                    "name": name,
                    "reason": reason,
                    "seed_rank": rank,
                    "seed_weight": 1 / rank,
                    "source_note": "curated_public_hot_seed",
                }
            )
    frame = pd.DataFrame(rows)
    if frame.empty:
        return frame
    frame["symbol"] = frame["symbol"].astype(str).str.zfill(6)
    frame = frame[frame["symbol"].map(_valid_symbol)]
    return frame.sort_values(["theme", "seed_rank", "symbol"]).reset_index(drop=True)


def symbols_for_themes(themes: str | Iterable[str] = "hot") -> list[str]:
    frame = build_theme_universe(themes)
    if frame.empty:
        return []
    return sorted(frame["symbol"].astype(str).unique().tolist())


def theme_universe_summary(frame: pd.DataFrame) -> pd.DataFrame:
    if frame.empty:
        return pd.DataFrame(columns=["theme", "theme_group", "rows", "unique_symbols", "top_seed_weight"])
    return (
        frame.groupby(["theme", "theme_group"], as_index=False)
        .agg(
            rows=("symbol", "size"),
            unique_symbols=("symbol", "nunique"),
            top_seed_weight=("seed_weight", "max"),
        )
        .sort_values(["theme_group", "theme"])
        .reset_index(drop=True)
    )


def symbol_theme_membership(frame: pd.DataFrame) -> pd.DataFrame:
    if frame.empty:
        return pd.DataFrame(columns=["symbol", "name", "theme_count", "themes", "reasons"])
    membership = (
        frame.groupby("symbol")
        .agg(
            name=("name", "first"),
            theme_count=("theme", "nunique"),
            themes=("theme", lambda values: ";".join(_unique(values))),
            reasons=("reason", lambda values: ";".join(_unique(values))),
        )
        .reset_index()
        .sort_values(["theme_count", "symbol"], ascending=[False, True])
        .reset_index(drop=True)
    )
    return membership


def _resolve_theme_names(themes: str | Iterable[str]) -> list[str]:
    if isinstance(themes, str):
        names = [item.strip() for item in themes.split(",") if item.strip()]
    else:
        names = [str(item).strip() for item in themes if str(item).strip()]
    selected: list[str] = []
    for name in names or ["hot"]:
        key = name.lower().replace(" ", "_")
        if key in THEME_ALIASES:
            selected.extend(THEME_ALIASES[key])
        else:
            selected.append(key.replace("-", "_"))
    return _unique(selected)


def _valid_symbol(symbol: str) -> bool:
    return bool(re.fullmatch(r"\d{6}", str(symbol)))


def _theme_group(theme: str) -> str:
    if theme in CORE_HOT_THEME_NAMES:
        return "core_hot"
    if theme in PROFESSIONAL_THEME_NAMES:
        return "professional_hot"
    return "expanded_hot"


def _unique(values: Iterable[object]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for value in values:
        text = str(value)
        if text not in seen:
            out.append(text)
            seen.add(text)
    return out
